"""Stage the experimental LAN modules into the local engine checkout.

This does not commit, overwrite a user's existing unrelated file, or modify a
packaged installation. It is only for opt-in builds from this checkout.
"""
from pathlib import Path
import shutil
import subprocess
root=Path(__file__).resolve().parents[2];lab=root/'tools/lan-lab';host=root/'engine/dm/host';dest=host/'spple_lan'
engine=root/'engine'
if not (engine/'.git').exists():
 raise SystemExit('Sync the upstream engine checkout with tools/engine.py first')
patch=lab/'ldn-engine-integration.patch'
apply=['git','-C',str(engine),'apply']
already_applied=subprocess.run([*apply,'--check','--reverse',str(patch)],capture_output=True)
if already_applied.returncode:
 check=subprocess.run([*apply,'--check',str(patch)],capture_output=True,text=True)
 if check.returncode:
  raise SystemExit('Cannot apply the LAN engine changes to this checkout:\n'+check.stderr)
 subprocess.run([*apply,str(patch)],check=True)
dest.mkdir(exist_ok=True)
for src in sorted((lab/'src').glob('*')):
 if src.suffix not in ('.c','.h'):continue
 shutil.copyfile(src,dest/src.name)
 if src.suffix=='.c':
  proxy=host/('hle_spple_lan_'+src.stem+'.c')
  content='/* Generated by stage_engine_sources.py; experimental opt-in LAN. */\n#include "spple_lan/'+src.name+'"\n'
  if proxy.exists() and proxy.read_text(encoding='utf-8')!=content:raise SystemExit('refusing to overwrite '+str(proxy))
  proxy.write_bytes(content.encode())
bootstrap=host/'hle_spple_lan_bootstrap.c';content=(lab/'engine_bootstrap.c.in').read_bytes()
if bootstrap.exists() and not bootstrap.read_bytes().startswith(b'/* Experimental LAN runtime, explicitly enabled with DM_LAN=1. */'):raise SystemExit('refusing to overwrite '+str(bootstrap))
bootstrap.write_bytes(content)
print('Staged experimental LAN modules in',host)
